def calc_indicator_metrics(cfg: Dict[str, Any], agency: str, actual_override: Optional[float] = None) -> Dict[str, Any]:
    """
    단일 지표를 선택된 평가주관('행안부' 또는 '서울시') 기준으로 계산.
    - 기본값(3분기 결재본 실적)과 동일하면 결재본 공식 달성률·공식 득점을 그대로 사용하여
      엑셀 결재본 합계(행안부 38.40 / 33.73점, 서울시 50.00 / 46.13점)와 100% 일치시킴.
    - 사용자가 실적을 수정(시뮬레이션)한 경우에만 변경된 달성률 비례로 예상 득점을 재산출함.
    """
    weight = cfg["moi_weight"] if agency == "행안부" else cfg["seoul_weight"]
    official_score = cfg["moi_score"] if agency == "행안부" else cfg["seoul_score"]

    target_a = cfg["target_a"]
    q3_target_b = cfg["q3_target_b"]
    default_c = cfg["q3_actual_c"]
    actual_c = float(actual_override) if actual_override is not None else default_c
    is_rev = cfg["is_reverse"]

    if abs(actual_c - default_c) < 1e-6:
        q3_rate = cfg["official_q3_rate"]
        annual_rate = cfg["official_annual_rate"]
        score = float(official_score or 0.0)
    else:
        if not is_rev:
            q3_rate = round((actual_c / q3_target_b) * 100.0, 1) if q3_target_b > 0 else 0.0
            annual_rate = round((actual_c / target_a) * 100.0, 1) if target_a > 0 else 0.0
        else:
            q3_rate = round((q3_target_b / actual_c) * 100.0, 1) if actual_c > 0 else 160.0
            annual_rate = round((target_a / actual_c) * 100.0, 1) if actual_c > 0 else 160.0
        ratio = min(1.0, max(0.0, q3_rate / 100.0))
        score = round(float(weight or 0.0) * ratio, 2)

    # 결재본 기준 4단계 달성 구간 판정 (100% 이상 / 95~99% / 90~95% / 90% 미만)
    if q3_rate >= 100.0:
        bucket = "100% 이상 달성"
        status = "정상"
    elif q3_rate >= 95.0:
        bucket = "95%~99% 달성"
        status = "정상"
    elif q3_rate >= 90.0:
        bucket = "90%~95% 달성"
        status = "주의"
    else:
        bucket = "90% 미만 (부진)"
        status = "위험"

    rem_q3 = max(0.0, q3_target_b - actual_c) if not is_rev else max(0.0, actual_c - q3_target_b)
    rem_annual = max(0.0, target_a - actual_c) if not is_rev else max(0.0, actual_c - target_a)

    return {
        "지표코드": cfg["id"],
        "부문": cfg["section"],
        "세부분류": cfg["sub_group"],
        "지표명": cfg["name"],
        "평가주관": agency,
        "공통여부": cfg["agency_label"],
        "소관부서": cfg["department"],
        "단위": cfg["unit"],
        "2026년 목표(A)": target_a,
        "3분기 목표(B)": q3_target_b,
        "3분기 실적(C)": actual_c,
        "3분기 달성률(C/B)": q3_rate,
        "연간 달성률(C/A)": annual_rate,
        "배점": float(weight or 0.0),
        "3분기 득점": score,
        "득점률(%)": round((score / weight) * 100.0, 1) if weight else 0.0,
        "연말목표 잔여량(A-C)": round(rem_annual, 2),
        "3분기목표 부족량(B-C)": round(rem_q3, 2),
        "달성구간": bucket,
        "상태": status,
    }


def build_agency_df(indicators_dict: Dict[str, Dict[str, Any]], agency: str, section_filter: str = "전체") -> pd.DataFrame:
    """선택된 평가주관('행안부' 또는 '서울시')에 해당하는 분기점검 정량지표만 추출 (절대 합산하지 않음)"""
    rows = []
    for ind_id, cfg in indicators_dict.items():
        if agency == "행안부" and cfg["moi_weight"] is None:
            continue
        if agency == "서울시" and cfg["seoul_weight"] is None:
            continue
        if section_filter != "전체" and cfg["section"] != section_filter:
            continue
        rows.append(calc_indicator_metrics(cfg, agency=agency))
    return pd.DataFrame(rows)


def evaluate_qualitative_text(qual_cfg: Dict[str, Any], report_text: str) -> Dict[str, Any]:
    text_clean = report_text.strip()
    text_no_space = re.sub(r"\s+", "", text_clean)
    req_kws = qual_cfg.get("required_keywords", [])
    matched = [kw for kw in req_kws if kw in text_clean or re.sub(r"\s+", "", kw) in text_no_space]
    missing = [kw for kw in req_kws if kw not in matched]
    kw_cov = (len(matched) / len(req_kws) * 100.0) if req_kws else 100.0

    pdca_markers = {
        "Plan (계획)": ["계획", "목표", "수립", "전략", "비전", "로드맵"],
        "Do (실행)": ["추진", "실시", "운영", "개최", "구축", "도입", "지원", "확대", "전환"],
        "Check (성과)": ["성과", "달성", "증가", "감소", "절감", "향상", "만족도", "수상", "%"],
        "Act (환류)": ["환류", "개선", "반영", "피드백", "보완", "정비", "고도화"],
    }
    pdca_scores = {k: min(100.0, round(sum(1 for m in v if m in text_clean) / 2.5 * 100.0, 1)) for k, v in pdca_markers.items()}
    pdca_avg = sum(pdca_scores.values()) / 4.0

    quant_matches = re.findall(r"\d+(?:[.,]\d+)?\s*(?:%|건|명|시간|톤|원|백만원|억원|점|회|개교|개소|개원|%p)", text_clean)
    quant_cnt = len(quant_matches)
    quant_score = min(100.0, quant_cnt * 18.0)

    length_factor = min(1.0, len(text_clean) / 160.0) if text_clean else 0.0
    total_pct = round(min(100.0, (kw_cov * 0.50 + pdca_avg * 0.30 + quant_score * 0.20) * (0.6 + 0.4 * length_factor)), 1) if text_clean else 0.0

    if total_pct >= 88.0:
        grade, coeff = "수 (탁월·100%)", 1.00
    elif total_pct >= 78.0:
        grade, coeff = "우 (우수·90%)", 0.90
    elif total_pct >= 68.0:
        grade, coeff = "양 (보통·80%)", 0.80
