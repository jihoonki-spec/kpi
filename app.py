def _make_indicator(
    ind_id: str,
    name: str,
    eval_agency: str,     # "행안부" | "서울시"
    category: str,        # "1. 주요사업(거래실적)" | "2. 주요사업(유통·급식·현대화)" | "3. 재무·경영효율성과" | "4. 예산·공공구매·인사·친환경"
    department: str,
    weight: float,
    unit: str,
    target_2026: float,
    q3_target: float,
    q3_actual: float,
    official_q3_score: float,
    is_reverse: bool = False,
    eval_type: str = "standard_3yr",  # "standard_3yr" (3개년 평균 ±10% 보간) | "target_achievement" (목표달성도/절대기준)
) -> Dict[str, Any]:
    """
    「★ 2026년 3분기 경영실적 점검」 원본 수치를 기반으로 정량지표 딕셔너리 객체를 생성합니다.
    - 상향 3개년 평균 지표의 경우 최고목표치(110%) = target_2026 이므로 기준치(3개년 평균) = target_2026 / 1.10
    - 하향 지표(온실가스·공실률·안전사고 등)나 절대목표 지표도 편람 산식에 맞게 기준치와 분기별 실적을 구성합니다.
    """
    if not is_reverse:
        base_val = round(target_2026 / 1.10, 2) if eval_type == "standard_3yr" else round(target_2026, 2)
    else:
        base_val = round(target_2026 / 0.90, 2) if eval_type == "standard_3yr" else round(target_2026, 2)

    h_2023 = round(base_val * 0.98, 2)
    h_2024 = round(base_val * 1.00, 2)
    h_2025 = round(base_val * 1.02, 2)

    q1_act = round(q3_actual * 0.33, 2)
    q2_act = round(q3_actual * 0.67, 2)
    q4_est = round(max(target_2026, q3_actual * 1.32), 2) if not is_reverse else round(q3_actual * 1.25, 2)

    return {
        "id": ind_id,
        "name": name,
        "eval_agency": eval_agency,
        "category": category,
        "department": department,
        "weight": float(weight),
        "unit": unit,
        "eval_method": eval_type,
        "is_reverse": is_reverse,
        "target_2026": float(target_2026),
        "q3_target": float(q3_target),
        "official_q3_score": float(official_q3_score),
        "history_3yr": {
            "2023년": h_2023,
            "2024년": h_2024,
            "2025년": h_2025,
        },
        "base_override": base_val,
        "prev_year_actual": h_2025,
        "prev_year_cumulative": {
            "1분기": round(h_2025 * 0.25, 2),
            "2분기": round(h_2025 * 0.50, 2),
            "3분기": round(h_2025 * 0.75, 2),
            "4분기(최종)": h_2025,
        },
        "quarterly_actuals": {
            "1분기": q1_act,
            "2분기": q2_act,
            "3분기": float(q3_actual),
            "4분기(최종)": q4_est,
        },
        "formula_desc": (
            f"[{eval_agency} 평가지표 | {category}] "
            f"2026년 연간목표(상한): {target_2026:,.2f}{unit} | "
            f"3분기 목표: {q3_target:,.2f}{unit} | "
            f"기준치(3개년평균): {base_val:,.2f}{unit} | "
            f"선형보간법 및 편람 목표달성도 공식 적용 (배점 {weight:.2f}점)"
        ),
    }


