# 4. AI 입력값 유효성 검증 (Smart Validation Engine)
# ==============================================================================
@dataclass
class ValidationMessage:
    level: str
    title: str
    detail: str


def validate_indicator_input(
    ind_cfg: Dict[str, Any],
    quarter: str,
    raw_input_text: str,
) -> Tuple[Optional[float], List[ValidationMessage], bool]:
    messages: List[ValidationMessage] = []
    cleaned = raw_input_text.strip().replace(",", "")
    if cleaned == "":
        messages.append(
            ValidationMessage(
                level="error",
                title="입력값 누락 오류 (Empty Value Error)",
                detail="실적 입력란이 비어 있습니다. 당해 분기 누적 실적을 숫자로 입력해 주십시오.",
            )
        )
        return None, messages, False

    try:
        val = float(cleaned)
    except ValueError:
        messages.append(
            ValidationMessage(
                level="error",
                title="숫자 형식 오류 (Invalid Number Format)",
                detail=f"입력된 값('{raw_input_text}')은 유효한 숫자가 아닙니다. 수치만 입력해 주십시오.",
            )
        )
        return None, messages, False

    if val < 0:
        messages.append(
            ValidationMessage(
                level="error",
                title="음수 입력 오류 (Negative Value Error)",
                detail=f"입력된 실적({val:,.2f} {ind_cfg['unit']})이 음수(-)입니다. 실적은 0 이상이어야 합니다.",
            )
        )
        return None, messages, False

    unit = ind_cfg["unit"]
    prev_sync = float(
        ind_cfg.get("prev_year_cumulative", {}).get(
            quarter, ind_cfg.get("prev_year_actual", compute_base_value(ind_cfg))
        )
    )
    if prev_sync > 0 and val > 0:
        ratio_sync = val / prev_sync
        if ratio_sync >= 10.0:
            messages.append(
                ValidationMessage(
                    level="warning",
                    title=f"🚨 단위({unit}/천원·kg·원) 오입력 경고 [전년 대비 10배 이상 과대]",
                    detail=(
                        f"입력값 **{val:,.2f} {unit}**은(는) 전년 동기 기준(**{prev_sync:,.2f} {unit}**) 대비 "
                        f"**{ratio_sync:,.1f}배** 큽니다. `{unit}` 단위를 하위 단위(kg, 원 등)로 잘못 입력하지 않았는지 확인하십시오!"
                    ),
                )
            )
        elif ratio_sync <= 0.10:
            messages.append(
                ValidationMessage(
                    level="warning",
                    title=f"🚨 단위({unit}) 오입력 경고 [전년 대비 1/10 이하 과소]",
                    detail=(
                        f"입력값 **{val:,.2f} {unit}**은(는) 전년 동기 기준(**{prev_sync:,.2f} {unit}**)의 "
                        f"**{ratio_sync * 100:.2f}% (1/10 이하)** 수준입니다. 단위 축소 오입력 여부를 확인하십시오!"
                    ),
                )
            )

    eval_res = evaluate_indicator(ind_cfg, quarter=quarter, actual_override=val)
    if eval_res.achievement_rate < 70.0 or eval_res.q3_target_rate < 85.0:
        messages.append(
            ValidationMessage(
                level="warning",
                title="⚠️ 추세 이상 감지: 목표 미달 위험 경고",
                detail=(
                    f"[{quarter}] 분기목표 대비 달성률이 **{eval_res.q3_target_rate:.1f}%** "
                    f"(연간 기준치 대비 **{eval_res.achievement_rate:.1f}%**)로 목표 미달 위험 구간입니다. "
                    f"소관부서({ind_cfg.get('department', '')})의 4분기 실적 만회 대책 수립이 필요합니다."
                ),
            )
        )

    if not messages:
        messages.append(
            ValidationMessage(
                level="success",
                title="✅ AI 스마트 유효성 검증 통과 (정상 범위)",
                detail=(
                    f"단위 정합성 및 달성률(분기목표 대비 {eval_res.q3_target_rate:.1f}%)이 모두 정상 범위 내에 있습니다. "
                    f"산출 득점: **{eval_res.score:.3f}점 / {eval_res.weight:.2f}점**"
                ),
            )
        )

    return val, messages, True


