def build_summary_dataframe(
    indicators_dict: Dict[str, Dict[str, Any]],
    quarter: str,
    scoring_standard: str = "분기목표 대비 점검득점(공사 3분기 점검표 기준)",
    agency_filter: str = "전체",
    category_filter: str = "전체",
) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for ind_id, cfg in indicators_dict.items():
        if agency_filter != "전체" and cfg.get("eval_agency") != agency_filter:
            continue
        if category_filter != "전체" and cfg.get("category") != category_filter:
            continue

        res = evaluate_indicator(cfg, quarter=quarter, scoring_standard=scoring_standard)
        remaining_for_max = (
            max(0.0, res.upper_target - res.actual_value)
            if not res.is_reverse
            else max(0.0, res.actual_value - res.upper_target)
        )
        rows.append(
            {
                "지표코드": res.indicator_id,
                "평가주관": res.eval_agency,
                "지표분류": res.category,
                "지표명": res.indicator_name,
                "소관부서": res.department,
                "배점": res.weight,
                "단위": res.unit,
                "지표성격": "하향(역산)" if res.is_reverse else "상향(일반)",
                "기준치(3개년평균)": res.base_value,
                "최저목표치(하한)": res.lower_target,
                "2026년 목표(A)": res.upper_target,
                "3분기 목표(B)": res.q3_target,
                f"{quarter} 실적(C)": res.actual_value,
                "3분기 달성률(C/B, %)": res.q3_target_rate,
                "연간 달성률(C/A, %)": res.annual_target_rate,
                "기준치 대비 달성률(%)": res.achievement_rate,
                "산출 득점": res.score,
                "득점률(%)": res.score_ratio,
                "평어구간": res.grade_label,
                "만점 잔여실적": round(remaining_for_max, 2),
                "상태": res.status_level,
                "상태사유": res.status_badge_reason,
            }
        )
    return pd.DataFrame(rows)


def generate_sample_audit_excel_df(
    indicators_dict: Dict[str, Dict[str, Any]],
    quarter: str,
    inject_human_errors: bool = True,
) -> pd.DataFrame:
    df = build_summary_dataframe(
        indicators_dict,
        quarter=quarter,
        scoring_standard="연간 편람 선형보간 공식 즉시 적용",
    )
    audit_rows: List[Dict[str, Any]] = []
    for _, row in df.iterrows():
        base_val = float(row["기준치(3개년평균)"])
        lower_val = float(row["최저목표치(하한)"])
        upper_val = float(row["2026년 목표(A)"])
        actual_val = float(row[f"{quarter} 실적(C)"])
        is_rev = "하향" in str(row["지표성격"])
        sys_sc, _, _, _, _ = calculate_linear_interpolation_score(
            actual=actual_val,
            base_value=base_val,
            weight=float(row["배점"]),
            is_reverse=is_rev,
            upper_override=upper_val,
            lower_override=lower_val,
        )
        score_val = sys_sc
        rate_val = float(row["3분기 달성률(C/B, %)"])
        error_note = "정상 (수식 일치)"

        if inject_human_errors:
            if row["지표명"] == "가락 청과 거래물량":
                upper_val = round(base_val * 1.05, 1)
                score_val = round(float(row["배점"]) * 0.92, 4)
                error_note = "[수기오류 적발] 최고목표치(105% 오적용) 및 선형보간 수식 왜곡"
            elif row["지표명"] == "가락 수산 거래물량":
                score_val = round(float(row["배점"]) * (actual_val / upper_val), 4)
                error_note = "[수기오류 적발] 편람 하한선(60%) 미적용·단순비례식 오산출"
            elif row["지표명"] == "출하전 안전성검사 전환율":
                rate_val = round(rate_val + 8.5, 1)
                score_val = round(score_val + 0.35, 4)
                error_note = "[수기오류 적발] 분모 셀 참조 밀림으로 인한 달성률·득점 과대계상"

        audit_rows.append(
            {
                "평가주관": row["평가주관"],
                "지표분류": row["지표분류"],
                "지표명": row["지표명"],
                "소관부서": row["소관부서"],
                "배점": row["배점"],
                "단위": row["단위"],
                "지표성격": row["지표성격"],
                "수기_기준치": base_val,
                "수기_최저목표치": lower_val,
                "수기_최고목표치": upper_val,
                "수기_당해실적": actual_val,
                "수기_달성률(%)": rate_val,
                "수기_산출득점": score_val,
                "비고(검증메모)": error_note,
            }
        )
    return pd.DataFrame(audit_rows)


def to_excel_bytes(df: pd.DataFrame, sheet_name: str = "경영성과팀_정량실적") -> bytes:
    buffer = io.BytesIO()
    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        df.to_excel(writer, index=False, sheet_name=sheet_name)
    return buffer.getvalue()


